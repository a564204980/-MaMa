import fs from 'node:fs';
import {readPNG,writePNG,cut} from './pack-characters.mjs';
const source=readPNG('assets/characters/girl-rig-v1.png');
for(let p=0;p<source.data.length;p+=4){const r=source.data[p],g=source.data[p+1],b=source.data[p+2];
 if(g>100&&g>r*1.35&&g>b*1.35)source.data[p+3]=0;
}
const xs=[0,320,525,680,825,980,1120,1290,1440,1595,1774],ys=[0,305,558,887];
const atlas=Buffer.alloc(960*288*4),frames=[];
for(let row=0;row<3;row++)for(let col=0;col<10;col++){
 const w=xs[col+1]-xs[col],h=ys[row+1]-ys[row],data=Buffer.alloc(w*h*4);
 for(let y=0;y<h;y++)source.data.copy(data,y*w*4,((ys[row]+y)*source.w+xs[col])*4,((ys[row]+y)*source.w+xs[col+1])*4);
 const s=cut({w,h,data},0,0,1,1),ratio=Math.min(88/(s.r-s.l+1),88/(s.d-s.t+1));
 const dw=Math.round((s.r-s.l+1)*ratio),dh=Math.round((s.d-s.t+1)*ratio),ox=col*96+4,oy=row*96+4;
 for(let y=0;y<dh;y++)for(let x=0;x<dw;x++){
  const q=(Math.min(s.d,s.t+Math.floor(y/ratio))*w+Math.min(s.r,s.l+Math.floor(x/ratio)))*4;
  s.data.copy(atlas,((oy+y)*960+ox+x)*4,q,q+4);
 }
 frames.push({x:ox,y:oy,w:dw,h:dh});
}
writePNG('assets/images/player-rig.png',960,288,atlas);
fs.writeFileSync('src/gameplay/PlayerRigFrames.ts','// Generated by scripts/pack-player-rig.mjs\nexport const playerRigFrames = '+JSON.stringify(frames)+';\n');
console.log('Player rig bytes:',fs.statSync('assets/images/player-rig.png').size);
